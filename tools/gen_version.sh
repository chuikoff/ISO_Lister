#!/bin/sh
# gen_version.sh — POSIX equivalent of gen_version.ps1 for MinGW/box builds.
# usage: tools/gen_version.sh <output-dir>   (writes <output-dir>/version_auto.h)
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root}
describe=$(git -C "$root" describe --tags --long --abbrev=7 --dirty --always 2>/dev/null || true)
sha=$(git -C "$root" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)
dirty=0
[ -n "$(git -C "$root" status --porcelain 2>/dev/null)" ] && dirty=1
major=1; minor=0; patch=0; build=0
if echo "$describe" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+-[0-9]+-g[0-9a-fA-F]+(-dirty)?$'; then
    v=$(echo "$describe" | sed -E 's/^v([0-9]+)\.([0-9]+)\.([0-9]+)-([0-9]+)-g([0-9a-fA-F]+).*/\1 \2 \3 \4 \5/')
    set -- $v; major=$1; minor=$2; patch=$3; build=$4; sha=$5
elif echo "$describe" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$'; then
    v=$(echo "$describe" | sed -E 's/^v([0-9]+)\.([0-9]+)\.([0-9]+)$/\1 \2 \3/')
    set -- $v; major=$1; minor=$2; patch=$3; build=0
elif [ -n "$describe" ]; then
    major=0; minor=1; patch=0; build=$(git -C "$root" rev-list --count HEAD 2>/dev/null || echo 0)
fi
# VERSION (X.Y.Z): release being prepared wins over an older tag, build 0
if [ -f "$root/VERSION" ]; then
    base=$(tr -d ' \r\n' < "$root/VERSION")
    if echo "$base" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
        newer=$(printf '%s\n%s.%s.%s\n' "$base" "$major" "$minor" "$patch" | sort -t. -k1,1n -k2,2n -k3,3n | tail -1)
        if [ "$newer" = "$base" ] && [ "$base" != "$major.$minor.$patch" ]; then
            IFS=. read major minor patch <<EOV
$base
EOV
            build=0
        fi
    fi
fi
ver="$major.$minor.$patch.$build"
gsha=$sha
[ "$dirty" = 1 ] && [ "$sha" != unknown ] && gsha="$sha-dirty"
ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)
tmp="$out/version_auto.h.tmp"
cat > "$tmp" <<EOH
// Auto-generated by tools/gen_version.sh. Do not edit manually.
#ifndef ISO_LISTER_VERSION_AUTO_H
#define ISO_LISTER_VERSION_AUTO_H

#define ISO_LISTER_VER_MAJOR $major
#define ISO_LISTER_VER_MINOR $minor
#define ISO_LISTER_VER_PATCH $patch
#define ISO_LISTER_VER_BUILD $build

#define ISO_LISTER_VERSION_STR  "$ver"
#define ISO_LISTER_GIT_SHA      "$gsha"
#define ISO_LISTER_BUILD_TIMESTAMP "$ts"

#define ISO_LISTER_VERSION_WSTR         L"$ver"
#define ISO_LISTER_GIT_SHA_WSTR         L"$gsha"
#define ISO_LISTER_BUILD_TIMESTAMP_WSTR L"$ts"

#endif // ISO_LISTER_VERSION_AUTO_H
EOH
mv -f "$tmp" "$out/version_auto.h"
echo "version_auto.h generated: $ver ($gsha @ $ts)"
